// ---------- Детерминированный рандом ----------
function hash(str) {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return h >>> 0;
}

function makeRng(seed) {
  let s = seed >>> 0 || 1;
  return () => {
    s ^= s << 13; s >>>= 0;
    s ^= s >>> 17;
    s ^= s << 5;  s >>>= 0;
    return s / 4294967296;
  };
}

function pick(rng, arr) { return arr[Math.floor(rng() * arr.length)]; }
function int(rng, min, max) { return min + Math.floor(rng() * (max - min + 1)); }

function shuffled(rng, arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function fill(template, vars) {
  return template.replace(/\{(\w+)\}/g, (_, key) =>
    vars[key] !== undefined ? vars[key] : ""
  );
}

function roleKey(hero) {
  const r = String(hero.role || "").toLowerCase();
  if (r.includes("mid") || r.includes("мид")) return "mid";
  if (r.includes("offlane") || r.includes("хард")) return "offlane";
  if (r.includes("support") || r.includes("саппорт")) return "support";
  if (r.includes("carry") || r.includes("керри")) return "carry";
  if (r.includes("roam")) return "roamer";
  return "generic";
}

function tierOf(p) {
  if (p < 35) return "bad";
  if (p < 60) return "mid";
  if (p < 85) return "good";
  return "epic";
}

function makeStat(rng) {
  const pos = pick(rng, STATS_POS);
  const neg = pick(rng, STATS_NEG);
  return `+${int(rng, 12, 99)} к ${pos} · −${int(rng, 3, 45)} к ${neg}`;
}

function mmrFor(rng, percent) {
  if (percent < 35) return `−${int(rng, 25, 40)}`;
  if (percent < 60) return `−${int(rng, 8, 24)}`;
  if (percent < 85) return `+${int(rng, 4, 19)}`;
  return `+${int(rng, 20, 32)}`;
}

// ---------- Главная функция ----------
export function generateExtras({ hero, item, style, items = [], salt = 0 }) {
  const seedStr = [hero.id, item, style.name, items.join("~"), salt].join("|");
  const rng = makeRng(hash(seedStr));

  const buildTitle = `${pick(rng, BUILD_ADJ)} ${pick(rng, BUILD_NOUN)} ${pick(rng, BUILD_GEN)}`;
  const playerTitle = pick(rng, PLAYER_TITLES);
  const percent = int(rng, 3, 99);
  const tier = tierOf(percent);
  const verdict = pick(rng, VERDICTS[tier]);
  const mmr = mmrFor(rng, percent);

  const vars = {
    hero: hero.name,
    item,
    style: style.name,
    analogy: pick(rng, ANALOGIES),
  };

  const triple = fill(pick(rng, TRIPLE_TEMPLATES), vars);
  const styleLine = fill(pick(rng, STYLE_TEMPLATES), vars);
  const heroLine = pick(rng, HERO_LINES[hero.id] || ROLE_LINES[roleKey(hero)]);

  const sentence = pick(rng, SENTENCES);
  const excuse = pick(rng, EXCUSES);
  const teamQuote = pick(rng, TEAM_QUOTES);
  const enemyQuote = pick(rng, ENEMY_QUOTES);
  const epitaph = pick(rng, EPITAPHS);

  const timeline = [
    { min: "03:00", text: pick(rng, TL_EARLY) },
    { min: "10:00", text: pick(rng, TL_MID) },
    { min: "20:00", text: pick(rng, TL_LATE) },
  ];

  const templates = shuffled(rng, ITEM_TEMPLATES);
  const itemNotes = items.map((name, i) => ({
    name,
    note: fill(templates[i % templates.length], { item: name }),
    stat: makeStat(rng),
  }));

  return {
    buildTitle, playerTitle, percent, tier, verdict, mmr,
    triple, styleLine, heroLine,
    sentence, excuse, teamQuote, enemyQuote, epitaph, timeline,
    itemNotes,
  };
}